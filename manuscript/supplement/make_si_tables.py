    write("s20_cost_other", lines)

    # c: total hours by run
    classical = ["lr", "flic", "ridge", "gam", "lgbm"]
    tfm = ["tabpfn", "tabicl", "mitra"]
    side = ["tabpfn_t1", "tabicl_t1", "tabpfn_legacy"]
    lines = []
    for run, title in (("main", "Main run, 58 scenarios"), ("random", "Random-design tier, 1,000 designs"),
                       ("realdata", "Real-data run, 5 data set--outcome pairs")):
        d = h[h["run"] == run]
        cl = d[d["arm"].isin(classical)]["hours"].sum()
        gpu = d[d["arm"].isin(tfm) & (d["device"] == "cuda")]["hours"].sum()
        cpu = d[d["arm"].isin(tfm) & (d["device"] == "cpu")]["hours"].sum()
        sd = d[d["arm"].isin(side)]["hours"].sum()
        g = gof[gof["run"].isin([run] + (["main_subsamples"] if run == "main" else []))]
        gh = g["hours"].sum()
        w = (num(wall.loc[run, "hours"] / 24, 1) + " d") if run in wall.index else r"\multicolumn{1}{c}{$^c$}"
        lines.append(" & ".join([title, num(cl, 1), num(gpu, 1), num(cpu, 1), num(sd, 1), num(gh, 1), w]) + r"\\")
    write("s20_cost_totals", lines)
    log("S20 hours:\n" + h.round(2).to_string())
    log("S20 gof:\n" + gof.round(3).to_string())
    log("S20 wall:\n" + wall.to_string())


