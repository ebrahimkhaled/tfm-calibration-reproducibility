def log(msg):
    print(msg, flush=True)


def num(x, d=3, signed=False):
    if x is None or (isinstance(x, float) and not math.isfinite(x)) or pd.isna(x):
        return "--"
    s = f"{x:.{d}f}"
    if s.startswith("-"):
        if float(s) == 0:
            s = s[1:]
        else:
            return "$-$" + s[1:]
    return ("+" if signed and float(s) > 0 else "") + s


def intn(x):
    if pd.isna(x):
        return "--"
    return f"{int(round(x)):,}".replace(",", "{,}")


def scen_parts(s):
    fam, pi, n = s.split("_")
    return fam, int(pi[2:]), int(n[1:])


def scen_short(s):
    fam, pi, n = scen_parts(s)
    return f"{fam}/{pi}/{n}"


def scen_cells(s):
    fam, pi, n = scen_parts(s)
    return f"{fam} & {pi} & {n}"


def write(name, lines):
    p = OUT / f"{name}.tex"
    p.write_text("% generated by make_si_tables.py; do not edit by hand\n" + "\n".join(lines) + "\n",
                 encoding="utf-8")
    log(f"written {p.relative_to(REB)} ({len(lines)} lines)")


def csv(name):
    p = SUM / f"{name}.parquet"
    return pd.read_parquet(p) if p.exists() else pd.read_csv(SUM / f"{name}.csv")


# ------------------------------------------------------------------ S5 fit outcomes
def table_s5():
    f = pd.read_csv(SUM / "fit_counts.csv")
    base = ["oracle", "lr", "flic", "ridge", "gam", "lgbm", "lgbm_raw", "tabpfn", "tabicl", "mitra",
            "tabpfn_t1", "tabicl_t1", "tabpfn_legacy"]
    rand = f["scenario"].str.match(r"^R\d+$")
    lines = []
    for title, sub in (("Main design (58 scenarios)", f[~rand]), ("Random-design tier (1,000 designs, one replicate each)", f[rand])):
        lines.append(r"\multicolumn{10}{@{}l}{\textit{" + title + r"}}\\")
        g = sub.groupby("arm")[["R", "ok", "degenerate", "failed", "not_run", "platt_fallback", "lambda_at_edge",
                                "small_n_flag", "any_boundary_prediction"]].sum()
        for a in base:
            if a not in g.index:
                continue
            r = g.loc[a]
            lines.append(" & ".join([LABEL[a], intn(r.R), intn(r.ok), intn(r.degenerate), intn(r.failed),
                                     intn(r.not_run), intn(r.platt_fallback), intn(r.lambda_at_edge),
                                     intn(r.small_n_flag), intn(r.any_boundary_prediction)]) + r"\\")
        lines.append(r"\midrule")
    # failures by scenario (main design)
    lines.append(r"\multicolumn{10}{@{}l}{\textit{Scenarios with failed fits (shape/event rate in \%/$n$: number failed of $R$); $\dagger$ more than 5\% failed}}\\")
    fm = f[~rand & f["arm"].isin(base)]
    for a in base:
        d = fm[(fm["arm"] == a) & (fm["failed"] > 0)]
        if not len(d):
            continue
        items = []
        for _, r in d.sort_values("scenario", key=lambda s: s.map(lambda x: ALL_SC.index(x) if x in ALL_SC else 999)).iterrows():
            items.append(f"{scen_short(r.scenario)}: {int(r.failed)} of {int(r.R)}" + (r"$^\dagger$" if bool(r.fail_flag) else ""))
        lines.append(LABEL[a] + r" & \multicolumn{9}{p{0.76\textwidth}@{}}{" + "; ".join(items) + r"}\\")
    lines.append(r"\midrule")
    # ladder levels at m = 100
    lines.append(r"\multicolumn{10}{@{}l}{\textit{Recalibration levels that could not be fitted on the 100-row local sample (main design; none at $m=500$)}}\\")
    for a in ["flic", "tabpfn", "tabicl", "mitra"]:
        cells = []
        for lev, nm in (("R1", "intercept"), ("R2", "logistic"), ("R3", "isotonic")):
            d = fm_l = f[~rand & (f["arm"] == f"{a}__{lev}_m100")]
            tot = f[~rand & (f["arm"] == a)]["R"].sum()
            cells.append(f"{nm} {intn(d['failed'].sum())}")
        lines.append(LABEL[a] + r" & \multicolumn{9}{l@{}}{" + "; ".join(cells) + f" (of {intn(f[~rand & (f['arm'] == a + '__R1_m100')]['R'].sum())} usable fits)" + r"}\\")
    write("s5_fits", lines)
    # device of TabPFN-3.5
    fits = pd.read_parquet(TAB / "fits.parquet", columns=["scenario", "arm", "device", "tier"])
    t = fits[(fits["arm"] == "tabpfn")]
    main = t[t["scenario"].isin(ALL_SC)].groupby("scenario")["device"].agg(lambda s: "/".join(sorted(set(s.dropna()))))
    gpu = [scen_short(s) for s in ALL_SC if main.get(s) == "cuda"]
    cpu = [scen_short(s) for s in ALL_SC if main.get(s) == "cpu"]
    mixed = [f"{scen_short(s)} ({main.get(s)})" for s in ALL_SC if main.get(s) not in ("cuda", "cpu")]
    rt = t[~t["scenario"].isin(ALL_SC)]["device"].value_counts()
    dev = [r"\textit{Graphics card} (" + str(len(gpu)) + " scenarios): " + ", ".join(gpu) + ".",
           r"\textit{Central-processor workers} (" + str(len(cpu)) + " scenarios): " + ", ".join(cpu) + "."]
    if mixed:
        dev.append(r"\textit{Both}: " + ", ".join(mixed) + ".")
    dev.append(f"Random-design tier: graphics card in {intn(rt.get('cuda', 0))} designs and central-processor workers in {intn(rt.get('cpu', 0))}.")
    write("s5_device", [r"\par ".join(dev)])
    log(f"S5 device: gpu {len(gpu)} cpu {len(cpu)} mixed {mixed}")


