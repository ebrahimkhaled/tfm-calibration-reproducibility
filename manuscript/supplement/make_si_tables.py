def mean_int(x, mult=1e3, d=1):
    x = pd.to_numeric(pd.Series(x), errors="coerce").dropna()
    if len(x) < 2:
        return "--"
    mu, h = x.mean(), 1.96 * x.std(ddof=1) / np.sqrt(len(x))
    return num(mu * mult, d, signed=True) + r"\,{\tiny[" + num((mu - h) * mult, d, signed=True) + ", " + num((mu + h) * mult, d, signed=True) + "]}"


